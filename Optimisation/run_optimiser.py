def run_all(df: pd.DataFrame, target_date: str = None) -> pd.DataFrame:
    """Iterate over all days, chain reservoir levels, return full result DataFrame."""
    import datetime as _dt

    print("Computing seasonal targets...")
    season_targets    = compute_seasonal_targets(df)
    season_production = compute_seasonal_production(df) if MODE == 'WATER_LEVEL' else {}

    solver         = get_solver() if MODE == 'WATER_VALUE' else None
    batt_solver    = get_battery_solver() if BATTERY_ACTIVE else None
    prod_fc_solver = get_prod_fc_solver() if PRODUCTION_FORECAST == 'LP_OPTIMISED' else None
    prev_soc       = SOC_INITIAL if BATTERY_ACTIVE else None
    total_discharged_kwh = 0.0

    days = sorted(df['DateTime'].dt.date.unique())
    if target_date:
        days = [d for d in days if str(d) == target_date]
        if not days:
            print(f"ERROR: date '{target_date}' not found in data.")
            sys.exit(1)

    results     = []
    prev_lb     = None
    prev_lh     = None
    failed_days = 0

    # Monthly peak import state (Leistungsentgelt)
    running_peak_kW = 0.0   # highest 15-min avg import seen so far this calendar month
    current_month   = None  # track month boundary for reset

    for i, day in enumerate(days, 1):
        day_df = df[df['DateTime'].dt.date == day].copy()

        # Reset monthly peak at calendar month boundary
        if day.month != current_month:
            running_peak_kW = 0.0
            current_month   = day.month

        t_lb, t_lh = season_targets.get(day, (None, None))

        if t_lb is None: t_lb = float(day_df['Bidmi_mm'].iloc[0])
        if t_lh is None: t_lh = float(day_df['Haselholz_mm'].iloc[0])

        lb0 = prev_lb if prev_lb is not None else float(day_df['Bidmi_mm'].iloc[0])
        lh0 = prev_lh if prev_lh is not None else float(day_df['Haselholz_mm'].iloc[0])

        # Build battery config for this day (carries today's starting SOC).
        # INTRADAY battery is co-simulated inside dispatch_day.
        # DAY_AHEAD battery is fully independent → dispatch_day ignores it.
        if BATTERY_ACTIVE:
            battery_cfg = BatteryConfig(mode=BATTERY_MODE, soc0=prev_soc,
                                        cycle_cost_eur_kwh=CYCLE_COST_EUR_KWH)
        else:
            battery_cfg = None

        seas_prod = season_production.get(day) if MODE == 'WATER_LEVEL' else None

        # Day-ahead production forecast override (LP-optimised schedule).
        # Replaces Forecast_kW with the output of a midnight day-ahead LP that
        # uses yesterday's actual reservoir levels, real inflows, forecast
        # consumption, DA prices, rolling-mean BG forecasts, the running monthly
        # peak, and the seasonal end-of-day targets.
        if PRODUCTION_FORECAST == 'LP_OPTIMISED':
            optimal_fc = compute_optimal_forecast(
                day_df, lb0, lh0, t_lb, t_lh,
                running_peak_kW=running_peak_kW,
                solver=prod_fc_solver,
            )
            day_df['Forecast_kW'] = optimal_fc

        day_df = dispatch_day(
            day_df, lb0, lh0, t_lb, t_lh,
            solver=solver,
            battery_cfg=battery_cfg,
            seasonal_prod=seas_prod,
            running_peak_kW=running_peak_kW,
        )

        # Read hydro chain attributes before any reset_index can drop them
        prev_lb = getattr(day_df, '_opt_lb_end', None)
        prev_lh = getattr(day_df, '_opt_lh_end', None)
        dev_b   = getattr(day_df, '_dev_b',      float('nan'))
        dev_h   = getattr(day_df, '_dev_h',      float('nan'))

        # Battery post-dispatch
        batt_str = ""
        if BATTERY_ACTIVE:
            if BATTERY_MODE == 'INTRADAY':
                # Co-simulation already done inside dispatch_day.
                prev_soc       = getattr(day_df, '_batt_soc_end', prev_soc)
                discharged_kwh = day_df['Batt_Discharge_kW'].sum() * TIMESTEP_HOURS

            else:  # DAY_AHEAD — fully independent LP, run now
                day_df, prev_soc, discharged_kwh = dispatch_day_battery(
                    day_df, prev_soc, batt_solver, mode=BATTERY_MODE)

            total_discharged_kwh += discharged_kwh
            cycles_today = discharged_kwh / CYCLE_KWH
            batt_rev     = day_df['Batt_Revenue_EUR'].sum()
            batt_str     = f"  batt {batt_rev:+.2f} EUR  cyc {cycles_today:.2f}"

        # -----------------------------------------------------------------------
        # Grid exchange power columns
        # P_Exchange_kW > 0 → importing from grid; < 0 → exporting to grid
        # -----------------------------------------------------------------------
        batt_net = day_df['Batt_Net_kW'] if 'Batt_Net_kW' in day_df.columns else 0.0
        day_df['P_Exchange_kW'] = (
            day_df['Consumption_kW'] - day_df['Opt_M2_kW'] - day_df['Opt_M1_kW'] - batt_net
        )
        day_df['P_Import_kW'] = day_df['P_Exchange_kW'].clip(lower=0.0)

        # Hydro-only counterfactual: what the meter would show without the battery,
        # holding today's hydro dispatch fixed. Used to attribute peak-fee savings.
        day_df['P_Import_NoBatt_kW'] = (
            day_df['Consumption_kW'] - day_df['Opt_M2_kW'] - day_df['Opt_M1_kW']
        ).clip(lower=0.0)

        # Reference (historical operator) counterfactual: what the meter actually
        # showed historically. Drives the reference peak fee for comparison.
        day_df['P_Import_Ref_kW'] = (
            day_df['Consumption_kW'] - day_df['Ref_M2_kW'] - day_df['Ref_M1_kW']
        ).clip(lower=0.0)

        # Day-ahead scheduled flow (locked at midnight via the DA bid)
        # DA_Import_kW : electricity bought on the DA market (>0 when buying)
        # DA_Export_kW : electricity sold on the DA market (>0 when selling)
        # Imbalance_Import_kW : real-time deviation from the DA schedule
        #                       (>0 when more import than scheduled / less export)
        da_net = day_df['Forecast_kW'] - day_df['Forecast_Consumption_kW']
        day_df['DA_Import_kW']        = (-da_net).clip(lower=0.0)
        day_df['DA_Export_kW']        = ( da_net).clip(lower=0.0)
        day_df['Imbalance_Import_kW'] = (day_df['P_Exchange_kW'] - (-da_net)).clip(lower=0.0)

        # 15-min block average import (3 consecutive 5-min steps per block)
        N_day    = len(day_df)
        B_BLOCKS = N_day // 3

        def _avg_15min(p):
            out = []
            for b in range(B_BLOCKS):
                v = float(p[3*b] + p[3*b+1] + p[3*b+2]) / 3.0
                out.extend([v, v, v])
            rem = N_day - 3 * B_BLOCKS
            if rem > 0:
                v = float(p[3*B_BLOCKS:].mean())
                out.extend([v] * rem)
            return out

        p15_expanded        = _avg_15min(day_df['P_Import_kW'].values)
        p15_nobatt_expanded = _avg_15min(day_df['P_Import_NoBatt_kW'].values)
        p15_ref_expanded    = _avg_15min(day_df['P_Import_Ref_kW'].values)
        day_df['P_Import_15min_kW']        = p15_expanded
        day_df['P_Import_NoBatt_15min_kW'] = p15_nobatt_expanded
        day_df['P_Import_Ref_15min_kW']    = p15_ref_expanded

        # Peak-tariff time window: only blocks whose timestamps lie in
        # [PEAK_TARIFF_HOUR_START, PEAK_TARIFF_HOUR_END) count toward the bill.
        hours          = day_df['DateTime'].dt.hour.values
        in_window_mask = (hours >= PEAK_TARIFF_HOUR_START) & (hours < PEAK_TARIFF_HOUR_END)
        day_df['In_Peak_Window']                  = in_window_mask.astype(int)
        day_df['P_Import_15min_Tariff_kW']        = [p if m else 0.0
                                                      for p, m in zip(p15_expanded,        in_window_mask)]
        day_df['P_Import_NoBatt_15min_Tariff_kW'] = [p if m else 0.0
                                                      for p, m in zip(p15_nobatt_expanded, in_window_mask)]
        day_df['P_Import_Ref_15min_Tariff_kW']    = [p if m else 0.0
                                                      for p, m in zip(p15_ref_expanded,    in_window_mask)]

        # Update running monthly peak — uses the window-masked column
        day_max_peak_15min = max(day_df['P_Import_15min_Tariff_kW']) if len(day_df) else 0.0
        running_peak_kW    = max(running_peak_kW, day_max_peak_15min)

        # Console progress
        opt_profit = day_df['Opt_Energy_Trading_EUR'].sum()
        ref_profit = day_df['Ref_Energy_Trading_EUR'].sum()
        gain       = opt_profit - ref_profit
        spill      = day_df['Opt_Spill_Bidmi_kWh'].sum() + day_df['Opt_Spill_Haselholz_kWh'].sum()
        spill_str  = f"  SPILL {spill:.0f} kWh" if spill > 0.1 else ""

        print(f"[{i:3}/{len(days)}] {day}  "
              f"tgt B={t_lb:.0f} H={t_lh:.0f}  "
              f"ref {ref_profit:+.2f} EUR  opt {opt_profit:+.2f} EUR  "
              f"gain {gain:+.2f} EUR  "
              f"dLB={dev_b:+.1f}mm dLH={dev_h:+.1f}mm"
              f"{spill_str}{batt_str}"
              f"  peak {day_max_peak_15min:.0f} kW")

        failed_days += getattr(day_df, '_failed', 0)
        results.append(day_df)

    result_df = pd.concat(results, ignore_index=True)
    result_df._total_discharged_kwh  = total_discharged_kwh
    result_df._failed_days           = failed_days
    return result_df


