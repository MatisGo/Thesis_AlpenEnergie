def save_output(opt_df: pd.DataFrame, output_path: str):
    """Save Results + Summary sheets to Excel."""
    opt_df['Opt_Total_Energy_Cost_EUR'] = opt_df['Opt_Energy_Trading_EUR'].cumsum()

    total_ref  = opt_df['Ref_Energy_Trading_EUR'].sum()
    total_opt  = opt_df['Opt_Energy_Trading_EUR'].sum()
    total_gain = total_opt - total_ref

    # Split DA market vs ID imbalance components (both Ref and Opt).
    # Imbalance further split: long = over-delivery sold at BG_Long (positive),
    # short = under-delivery bought at BG_Short (negative). long + short = subtotal.
    total_ref_da        = opt_df['Ref_DA_EUR'].sum()
    total_ref_imb_long  = opt_df['Ref_Imbalance_Long_EUR'].sum()
    total_ref_imb_short = opt_df['Ref_Imbalance_Short_EUR'].sum()
    total_ref_imb       = opt_df['Ref_Imbalance_EUR'].sum()
    total_opt_da        = opt_df['Opt_DA_Trading_EUR'].sum()
    total_opt_imb_long  = opt_df['Opt_Imbalance_Long_EUR'].sum()
    total_opt_imb_short = opt_df['Opt_Imbalance_Short_EUR'].sum()
    total_opt_imb       = opt_df['Opt_ID_Imbalance_EUR'].sum()

    daily_ref        = opt_df.groupby(opt_df['DateTime'].dt.date)['Ref_Energy_Trading_EUR'].sum()
    daily_opt        = opt_df.groupby(opt_df['DateTime'].dt.date)['Opt_Energy_Trading_EUR'].sum()
    days_opt_better  = (daily_opt > daily_ref).sum()
    days_ref_better  = (daily_opt < daily_ref).sum()

    ref_energy_kwh = ((opt_df['Ref_M2_kW'] + opt_df['Ref_M1_kW']) * TIMESTEP_HOURS).sum()
    opt_energy_kwh = opt_df['Opt_Production_kW'].sum() * TIMESTEP_HOURS
    energy_diff    = opt_energy_kwh - ref_energy_kwh

    total_spill_b   = opt_df['Opt_Spill_Bidmi_kWh'].sum()
    total_spill_h   = opt_df['Opt_Spill_Haselholz_kWh'].sum()
    total_spill     = total_spill_b + total_spill_h

    # Monthly peak import tariff (Leistungsentgelt)
    peak_rows           = []
    total_peak_cost     = 0.0
    total_peak_cost_ref = 0.0
    peak_savings_battery = 0.0   # EUR saved by the battery on the peak fee
    if 'P_Import_15min_Tariff_kW' in opt_df.columns:
        opt_df['Month_key'] = opt_df['DateTime'].dt.to_period('M')
        # Only in-window blocks (column already masked to 0 outside the window)
        monthly_peak = opt_df.groupby('Month_key')['P_Import_15min_Tariff_kW'].max()
        monthly_cost = monthly_peak * PEAK_TARIFF_EUR_KW
        total_peak_cost = monthly_cost.sum()

        # Reference (historical operator) peak fee — what was actually paid historically
        ref_monthly_peak = None
        if 'P_Import_Ref_15min_Tariff_kW' in opt_df.columns:
            ref_monthly_peak = opt_df.groupby('Month_key')['P_Import_Ref_15min_Tariff_kW'].max()
            ref_monthly_cost = ref_monthly_peak * PEAK_TARIFF_EUR_KW
            total_peak_cost_ref = ref_monthly_cost.sum()

        # Counterfactual: what the peak fee would have been without the battery,
        # holding today's hydro dispatch fixed. Difference = battery's peak savings.
        nobatt_cost_total = 0.0
        nobatt_monthly_peak = None
        if BATTERY_ACTIVE and 'P_Import_NoBatt_15min_Tariff_kW' in opt_df.columns:
            nobatt_monthly_peak = opt_df.groupby('Month_key')['P_Import_NoBatt_15min_Tariff_kW'].max()
            nobatt_monthly_cost = nobatt_monthly_peak * PEAK_TARIFF_EUR_KW
            nobatt_cost_total   = nobatt_monthly_cost.sum()
            peak_savings_battery = nobatt_cost_total - total_peak_cost

        opt_df.drop(columns=['Month_key'], inplace=True)

        peak_rows = [('--- Grid Import Peak Tariff (Leistungsentgelt) ---', '', '')]
        for period, pk_kw, pk_eur in zip(monthly_peak.index,
                                          monthly_peak.values,
                                          monthly_cost.values):
            peak_rows.append((str(period), f'{pk_kw:.1f} kW  ->  {pk_eur:.2f}', 'EUR'))
        peak_rows += [
            ('Total peak tariff cost (Opt)', f'{total_peak_cost:,.2f}',     'EUR'),
            ('Total peak tariff cost (Ref)', f'{total_peak_cost_ref:,.2f}', 'EUR'),
            ('Tariff rate',                  f'{PEAK_TARIFF_EUR_KW:.1f}',   'EUR/kW/month'),
        ]
        if BATTERY_ACTIVE and nobatt_monthly_peak is not None:
            peak_rows += [
                ('Peak fee without battery',  f'{nobatt_cost_total:,.2f}',     'EUR'),
                ('Battery peak savings',      f'{peak_savings_battery:+,.2f}', 'EUR'),
            ]
        peak_rows.append(('', '', ''))

    # Forecast drift (FORECAST and WATER_VALUE modes)
    drift_rows = []
    if 'Forecast_Drift_kW' in opt_df.columns:
        drift     = opt_df['Forecast_Drift_kW']
        drift_kwh = (drift * TIMESTEP_HOURS).sum()
        mae_kw    = drift.abs().mean()
        n         = len(drift)
        h_below   = (drift < -1.0).sum() * TIMESTEP_HOURS
        h_above   = (drift >  1.0).sum() * TIMESTEP_HOURS
        drift_rows = [
            ('--- Forecast Drift (simulated − forecast) ---', '', ''),
            ('Cumulative drift', f'{drift_kwh:+,.0f}',  'kWh'),
            ('Mean absolute error', f'{mae_kw:.1f}',    'kW per 5-min step'),
            ('Hours below forecast', f'{h_below:.1f}',  'h  (recovery active)'),
            ('Hours above forecast', f'{h_above:.1f}',  'h'),
            ('', '', ''),
        ]

    # Battery summary
    batt_rows = []
    if BATTERY_ACTIVE and 'Batt_Revenue_EUR' in opt_df.columns:
        total_batt_rev    = opt_df['Batt_Revenue_EUR'].sum()       # ID imbalance savings
        total_discharged  = getattr(opt_df, '_total_discharged_kwh', 0.0)
        total_cycles      = total_discharged / CYCLE_KWH
        total_charged_kwh = (opt_df['Batt_Charge_kW'] * TIMESTEP_HOURS).sum()
        # Battery contribution = ID imbalance savings + peak fee savings (both EUR)
        total_batt_value  = total_batt_rev + peak_savings_battery
        # Financial analysis
        n_days              = opt_df['DateTime'].dt.date.nunique()
        batt_capex          = CAPACITY_KWH * BATTERY_COST_PER_KWH
        annual_id_revenue   = total_batt_rev       * 365.0 / n_days
        annual_peak_savings = peak_savings_battery * 365.0 / n_days
        annual_revenue      = annual_id_revenue + annual_peak_savings   # used by NPV
        annual_om           = BATTERY_OM_EUR_KWH_YEAR * CAPACITY_KWH
        annual_cf           = annual_revenue - annual_om
        annual_cycles_sim   = total_cycles * 365.0 / n_days   # annualised from simulation

        # Capacity factor in year t: linear degradation per cycle.
        # cap_factor(t) = max(0, 1 - DEG_PER_CYCLE × cumulative_cycles_at_end_of_year_t)
        # cumulative cycles at end of year t = annual_cycles × t
        def cap_factor(t):
            return max(0.0, 1.0 - BATTERY_DEG_PER_CYCLE * annual_cycles_sim * t)

        # NPV: cash flow in year t = annual_cf × cap_factor(t), discounted at DISCOUNT_RATE
        npv               = -batt_capex + sum(
                                annual_cf * cap_factor(t) / (1 + DISCOUNT_RATE) ** t
                                for t in range(1, BATTERY_LIFETIME_YEARS + 1))
        simple_payback    = (batt_capex / annual_cf) if annual_cf > 0 else float('inf')

        # Lifetime kWh discharged also degrades each year with cap_factor
        annual_discharged = total_discharged * 365.0 / n_days
        lifetime_kwh      = sum(
                                annual_discharged * cap_factor(t)
                                for t in range(1, BATTERY_LIFETIME_YEARS + 1))
        lcos              = (batt_capex / lifetime_kwh) if lifetime_kwh > 0 else float('inf')
        capacity_end_life = round(cap_factor(BATTERY_LIFETIME_YEARS) * 100, 1)

        batt_rows = [
            ('--- Battery (BESS) ---', '', ''),
            ('Mode',                  BATTERY_MODE,                    ''),
            ('Capacity',              f'{CAPACITY_KWH:.1f}',           'kWh'),
            ('Round-trip efficiency', f'{ROUND_TRIP_EFF*100:.0f}',     '%'),
            ('Total charged',         f'{total_charged_kwh:,.1f}',     'kWh'),
            ('Total discharged',      f'{total_discharged:,.1f}',      'kWh'),
            ('Total cycles',          f'{total_cycles:.1f}',           'cycles'),
            ('ID imbalance revenue',  f'{total_batt_rev:+,.2f}',       'EUR'),
            ('Peak fee savings',      f'{peak_savings_battery:+,.2f}', 'EUR'),
            ('Total battery value',   f'{total_batt_value:+,.2f}',     'EUR (ID + peak)'),
            ('', '', ''),
            ('--- Battery Investment ---', '', ''),
            ('Days simulated',        f'{n_days}',                                     'days'),
            ('Annual cycles',         f'{annual_cycles_sim:.1f}',                      'cycles/year'),
            ('Annualised ID revenue', f'{annual_id_revenue:+,.2f}',                    'EUR/year'),
            ('Annualised peak savings', f'{annual_peak_savings:+,.2f}',                'EUR/year'),
            ('Annualised total revenue', f'{annual_revenue:+,.2f}',                    'EUR/year (used in NPV)'),
            ('O&M costs',             f'{BATTERY_OM_EUR_KWH_YEAR:.1f} EUR/kWh/yr  ->  {annual_om:,.0f}',  'EUR/year'),
            ('Annual cash flow',      f'{annual_cf:+,.2f}',                            'EUR/year'),
            (f'CAPEX  ({BATTERY_COST_PER_KWH:.0f} EUR/kWh)',
                                      f'{batt_capex:,.0f}',                            'EUR'),
            (f'NPV  ({BATTERY_LIFETIME_YEARS}y, {DISCOUNT_RATE*100:.0f}%, {BATTERY_DEG_PER_CYCLE*100:.4f}%/cyc)',
                                      f'{npv:+,.0f}',                                  'EUR'),
            ('Simple payback',        f'{simple_payback:.1f}' if simple_payback < 100 else '>100',
                                                                                        'years'),
            ('LCOS',                  f'{lcos:.3f}' if lcos < 9999 else 'N/A',         'EUR/kWh cycled'),
            (f'Capacity at yr {BATTERY_LIFETIME_YEARS}',
                                      f'{capacity_end_life:.1f}',                      '%'),
            ('', '', ''),
        ]

    summary_rows = [
        ('--- Profit / Cost ---', '', ''),
        ('Reference DA',              f'{total_ref_da:+.2f}',        'EUR'),
        ('Reference Imbalance Long',  f'{total_ref_imb_long:+.2f}',  'EUR'),
        ('Reference Imbalance Short', f'{total_ref_imb_short:+.2f}', 'EUR'),
        ('Reference Imbalance',       f'{total_ref_imb:+.2f}',       'EUR'),
        ('Reference total',           f'{total_ref:+.2f}',           'EUR'),
        ('Optimised DA',              f'{total_opt_da:+.2f}',        'EUR'),
        ('Optimised Imbalance Long',  f'{total_opt_imb_long:+.2f}',  'EUR'),
        ('Optimised Imbalance Short', f'{total_opt_imb_short:+.2f}', 'EUR'),
        ('Optimised Imbalance',       f'{total_opt_imb:+.2f}',       'EUR'),
        ('Optimised total',           f'{total_opt:+.2f}',           'EUR'),
        ('Optimizer gain',            f'{total_gain:+.2f}',          'EUR'),
        ('Days opt better',           days_opt_better,                ''),
        ('Days ref better',           days_ref_better,                ''),
        ('', '', ''),
        ('--- Energy Production ---', '', ''),
        ('Reference energy',   f'{ref_energy_kwh:,.0f}',  'kWh'),
        ('Optimised energy',   f'{opt_energy_kwh:,.0f}',  'kWh'),
        ('Difference',         f'{energy_diff:+,.0f}',    'kWh'),
        ('', '', ''),
        *peak_rows,
        *drift_rows,
        ('--- Spillage Losses ---', '', ''),
        ('Bidmi spillage',     f'{total_spill_b:,.0f}',  'kWh'),
        ('Haselholz spillage', f'{total_spill_h:,.0f}',  'kWh'),
        ('Total spillage',     f'{total_spill:,.0f}',    'kWh'),
        ('', '', ''),
        *batt_rows,
        ('--- Model ---', '', ''),
        ('Mode', MODE, ''),
    ]

    summary_df = pd.DataFrame(summary_rows, columns=['Metric', 'Value', 'Unit'])

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with pd.ExcelWriter(output_path, engine='openpyxl') as writer:
        opt_df.to_excel(writer, sheet_name='Results', index=False)
        summary_df.to_excel(writer, sheet_name='Summary', index=False)

    print(f"\nSaved: {output_path}")

    # ── Console summary  (subsections for readability) ──────────────────
    W = 56  # total width
    def _hdr(title):
        print(f"\n  +-- {title} " + "-" * (W - 7 - len(title)))

    print(f"\n{'='*W}")
    print(f"  Mode: {MODE}")

    _hdr("Hydro Energy Trading")
    print(f"  Reference DA      : {total_ref_da:+,.2f} EUR")
    print(f"  Reference Imb Long: {total_ref_imb_long:+,.2f} EUR")
    print(f"  Reference Imb Short:{total_ref_imb_short:+,.2f} EUR")
    print(f"  Reference Imb.    : {total_ref_imb:+,.2f} EUR")
    print(f"  Reference total   : {total_ref:+,.2f} EUR")
    print(f"  Optimised DA      : {total_opt_da:+,.2f} EUR")
    print(f"  Optimised Imb Long: {total_opt_imb_long:+,.2f} EUR")
    print(f"  Optimised Imb Short:{total_opt_imb_short:+,.2f} EUR")
    print(f"  Optimised Imb.    : {total_opt_imb:+,.2f} EUR")
    print(f"  Optimised total   : {total_opt:+,.2f} EUR")
    print(f"  Gain vs reference : {total_gain:+,.2f} EUR")

    _hdr("Production / Spill")
    print(f"  Ref energy        : {ref_energy_kwh/1000:,.1f} MWh")
    print(f"  Opt energy        : {opt_energy_kwh/1000:,.1f} MWh")
    print(f"  Total spill loss  : {total_spill/1000:,.1f} MWh")

    if drift_rows:
        _hdr("Forecast Tracking")
        print(f"  Forecast MAE      : {mae_kw:.1f} kW")
        print(f"  Cumulative drift  : {drift_kwh/1000:+,.1f} MWh")

    if peak_rows:
        _hdr("Grid Import Peak Tariff")
        print(f"  Peak fee (Ref)    : {total_peak_cost_ref:,.2f} EUR")
        print(f"  Peak fee (Opt)    : {total_peak_cost:,.2f} EUR")
        if BATTERY_ACTIVE and peak_savings_battery != 0.0:
            print(f"  Saved by battery  : {peak_savings_battery:+,.2f} EUR (vs hydro-only meter)")

    if batt_rows:
        _hdr("Battery (BESS)")
        print(f"  ID imbalance rev. : {total_batt_rev:+,.2f} EUR")
        print(f"  Peak fee savings  : {peak_savings_battery:+,.2f} EUR")
        print(f"  Total batt value  : {total_batt_value:+,.2f} EUR  ({n_days}d -> {annual_revenue:+,.0f} EUR/yr)")
        print(f"  Cycles            : {total_cycles:.1f}  ({total_discharged/1000:,.1f} MWh discharged)")

        _hdr("Battery Investment")
        print(f"  CAPEX             : {batt_capex:,.0f} EUR")
        print(f"  Annual cash flow  : {annual_cf:+,.2f} EUR/yr (incl. peak savings, after O&M)")
        print(f"  NPV ({BATTERY_LIFETIME_YEARS}y,{DISCOUNT_RATE*100:.0f}%)     : {npv:+,.0f} EUR")
        if simple_payback < 100:
            print(f"  Simple payback    : {simple_payback:.1f} years")
        else:
            print(f"  Simple payback    : >100 years")
        if lcos < 9999:
            print(f"  LCOS              : {lcos:.3f} EUR/kWh")
        else:
            print(f"  LCOS              : N/A")

    # ── Net total: hydro+battery profit, minus the peak fee actually paid ──
    if batt_rows:
        hydro_plus_batt = total_opt + total_batt_rev
        net_total       = hydro_plus_batt - total_peak_cost
        _hdr("NET TOTAL")
        print(f"  Hydro+Battery     : {hydro_plus_batt:+,.2f} EUR")
        print(f"  Peak fee          : {-total_peak_cost:+,.2f} EUR")
        print(f"  ─────────────────────────────────────")
        print(f"  NET TOTAL         : {net_total:+,.2f} EUR")
    else:
        net_total = total_opt - total_peak_cost
        _hdr("NET TOTAL")
        print(f"  Hydro profit      : {total_opt:+,.2f} EUR")
        print(f"  Peak fee          : {-total_peak_cost:+,.2f} EUR")
        print(f"  ─────────────────────────────────────")
        print(f"  NET TOTAL         : {net_total:+,.2f} EUR")

    print(f"{'='*W}")

    # Return a flat summary dict for Main_results.xlsx
    return {
        'Mode':                MODE,
        'Imbalance_Forecast':   IMBALANCE_FORECAST,
        'Production_Forecast':  PRODUCTION_FORECAST,
        'DA_Price_Forecast':    DA_PRICE_FORECAST,
        'Consumption_Forecast': CONSUMPTION_FORECAST,
        'Battery_Active':      BATTERY_ACTIVE,
        'Battery_Mode':       BATTERY_MODE            if BATTERY_ACTIVE else '-',
        'Capacity_kWh':       CAPACITY_KWH            if BATTERY_ACTIVE else 0,
        'C_Rate':             C_RATE                  if BATTERY_ACTIVE else '-',
        'RTE_pct':            round(ROUND_TRIP_EFF * 100) if BATTERY_ACTIVE else '-',
        'Deg_pct_per_cycle':  BATTERY_DEG_PER_CYCLE * 100  if BATTERY_ACTIVE else '-',
        'Lifetime_Years':     BATTERY_LIFETIME_YEARS  if BATTERY_ACTIVE else '-',
        'Discount_Rate_pct':  DISCOUNT_RATE * 100     if BATTERY_ACTIVE else '-',
        'OM_EUR_kWh_yr':      BATTERY_OM_EUR_KWH_YEAR  if BATTERY_ACTIVE else '-',
        'OM_Cost_EUR_Year':   annual_om                if batt_rows else 0,
        'Ref_DA_EUR':               round(total_ref_da,        2),
        'Ref_Imbalance_Long_EUR':   round(total_ref_imb_long,  2),
        'Ref_Imbalance_Short_EUR':  round(total_ref_imb_short, 2),
        'Ref_Imbalance_EUR':        round(total_ref_imb,       2),
        'Opt_DA_EUR':               round(total_opt_da,        2),
        'Opt_Imbalance_Long_EUR':   round(total_opt_imb_long,  2),
        'Opt_Imbalance_Short_EUR':  round(total_opt_imb_short, 2),
        'Opt_Imbalance_EUR':        round(total_opt_imb,       2),
        'Gain_EUR':                 round(total_gain,          2),
        'Days_Opt_Better': int(days_opt_better),
        'Days_Ref_Better': int(days_ref_better),
        'Opt_Energy_MWh':  round(opt_energy_kwh / 1000, 1),
        'Spill_MWh':       round(total_spill / 1000, 1),
        'Forecast_MAE_kW': round(mae_kw, 1) if drift_rows else '-',
        'Batt_Revenue_EUR':    round(total_batt_rev, 2)    if batt_rows else 0,
        'Batt_Cycles':         round(total_cycles, 1)      if batt_rows else 0,
        'Annual_Cycles':       round(annual_cycles_sim, 1) if batt_rows else 0,
        'Days_Simulated':      n_days                      if batt_rows else opt_df['DateTime'].dt.date.nunique(),
        'Annual_Revenue_EUR':  round(annual_revenue, 2)    if batt_rows else 0,
        'CAPEX_EUR':           round(batt_capex, 0)        if batt_rows else 0,
        'NPV_EUR':             round(npv, 0)               if batt_rows else 0,
        'Payback_Years':       round(simple_payback, 1)    if (batt_rows and simple_payback < 100) else ('>100' if batt_rows else 0),
        'LCOS_EUR_kWh':        round(lcos, 3)              if (batt_rows and lcos < 9999) else 0,
        'Capacity_EOL_pct':    capacity_end_life           if batt_rows else 0,
        'Peak_Tariff_EUR':         round(total_peak_cost,     2),
        'Ref_Peak_Tariff_EUR':     round(total_peak_cost_ref, 2),
        'Batt_Peak_Savings_EUR':   round(peak_savings_battery, 2) if BATTERY_ACTIVE else 0,
        'Net_Total_EUR':           round(net_total, 2),
        'Failed_Days':         getattr(opt_df, '_failed_days', 0),
        'Output_File':         os.path.basename(output_path),
    }


# ---------------------------------------------------------------------------
# Main results log  (one row per run, appended to Main_results.xlsx)
# ---------------------------------------------------------------------------

def append_main_results(output_dir: str, summary: dict):
    """Append one summary row to Output/Main_results.xlsx."""
    import datetime
    summary = {'Timestamp': datetime.datetime.now().strftime('%Y-%m-%d %H:%M'), **summary}
    row_df   = pd.DataFrame([summary])
    path     = os.path.join(output_dir, 'Main_results.xlsx')
    if os.path.exists(path):
        existing = pd.read_excel(path, engine='openpyxl')
        combined = pd.concat([existing, row_df], ignore_index=True)
    else:
        combined = row_df
    with pd.ExcelWriter(path, engine='openpyxl') as writer:
        combined.to_excel(writer, index=False)
    print(f"Main results updated: {path}")


