def _make_output_filename():
    """Build a short, descriptive filename from run parameters."""
    if IMBALANCE_FORECAST not in IMBALANCE_VARIANT_TAGS:
        raise ValueError(f"Unknown IMBALANCE_FORECAST '{IMBALANCE_FORECAST}'. "
                         f"Choices: {list(IMBALANCE_VARIANT_TAGS.keys())}")
    if DA_PRICE_FORECAST not in DA_PRICE_VARIANT_TAGS:
        raise ValueError(f"Unknown DA_PRICE_FORECAST '{DA_PRICE_FORECAST}'. "
                         f"Choices: {list(DA_PRICE_VARIANT_TAGS.keys())}")
    mode_short = {'FORECAST': 'FC', 'FORECAST_TEST': 'FCT',
                  'WATER_VALUE': 'WV', 'WATER_LEVEL': 'WL'}.get(MODE, MODE)
    if not BATTERY_ACTIVE:
        batt_str = 'NoBatt'
    else:
        batt_short = {'DAY_AHEAD': 'DA', 'INTRADAY': 'ID'}.get(BATTERY_MODE, BATTERY_MODE)
        kwh = int(round(CAPACITY_KWH))
        batt_str = f'{batt_short}_{kwh}kWh'
    pf_tag = {'OPERATOR': 'PFOP', 'LP_OPTIMISED': 'PFLP'}.get(PRODUCTION_FORECAST, PRODUCTION_FORECAST)
    # DA price forecast tag only meaningful when LP_OPTIMISED; always include for traceability.
    da_tag = {'PERFECT': 'DAP', 'MAPE_05': 'DAM05', 'MAPE_15': 'DAM15'}.get(
        DA_PRICE_FORECAST, DA_PRICE_FORECAST)
    return f'{mode_short}_{batt_str}_FC{IMBALANCE_FORECAST}_{pf_tag}_LF{CONSUMPTION_FORECAST}_{da_tag}.xlsx'

