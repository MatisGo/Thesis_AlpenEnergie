MODE = 'FORECAST'  # 'FORECAST', 'FORECAST_TEST', 'WATER_VALUE', 'WATER_LEVEL'

# ---------------------------------------------------------------------------
#  IMBALANCE-PRICE FORECAST VARIANT (for value-of-information study)
# ---------------------------------------------------------------------------
#   'REAL'         Perfect foresight — uses realised BG prices (upper bound)
#   'ROLLING_MEAN' Today's 7-day rolling mean shifted 1 day forward (R^2 ~ 0.06)
#   'R2_02'        Synthetic AR(1) noise at R^2 = 0.2 (naive-statistical level)
#   'R2_05'        Synthetic AR(1) noise at R^2 = 0.5 (modern ML target)
#   'R2_08'        Synthetic AR(1) noise at R^2 = 0.8 (near-perfect)
#
# Variants are pre-generated by generate_imbalance_forecasts.py into
# Input/imbalance_forecasts.xlsx and loaded by load_data().
IMBALANCE_FORECAST = 'ROLLING_MEAN'  # 'REAL' | 'ROLLING_MEAN' | 'R2_02' | 'R2_05' | 'R2_08'

# ---------------------------------------------------------------------------
#  PRODUCTION-FORECAST SOURCE (drives Forecast_kW and the DA bid)
# ---------------------------------------------------------------------------
#   'OPERATOR'     Use the DeepNN forecast already in matis_2025_.xlsx
#                  (mimics historical operator production)
#   'LP_OPTIMISED' Override Forecast_kW with an economically optimal schedule
#                  computed daily by production_forecast_lp.py — uses yesterday's
#                  actual reservoir end levels, real inflows (perfect knowledge),
#                  forecast consumption, DA prices, rolling-mean BG forecasts,
#                  running monthly peak, and seasonal end-of-day targets.
PRODUCTION_FORECAST = 'OPERATOR'  # 'OPERATOR' | 'LP_OPTIMISED'

# ---------------------------------------------------------------------------
#  CONSUMPTION-FORECAST VARIANT (for value-of-information study on load)
# ---------------------------------------------------------------------------
#   'PERFECT'  Zero-error forecast = real consumption (theoretical upper bound)
#   'CURRENT'  Existing CNN-LSTM forecast (WMAPE ~6%)
#   'MAPE_10'  Synthetic, hour-of-day-conditional AR(1) noise at WMAPE 10%
#   'MAPE_15'  Same at WMAPE 15%
#   'MAPE_20'  Same at WMAPE 20%
# Generated by generate_consumption_forecasts.py into
# Input/consumption_forecasts.xlsx and loaded by load_data().
CONSUMPTION_FORECAST = 'CURRENT'  # 'PERFECT' | 'CURRENT' | 'MAPE_10' | 'MAPE_15' | 'MAPE_20'

# ---------------------------------------------------------------------------
#  DA-PRICE FORECAST VARIANT (for value-of-information study on day-ahead price)
# ---------------------------------------------------------------------------
#   'PERFECT'  Zero-error forecast = real DA price (theoretical upper bound)
#   'MAPE_05'  Additive AR(1) noise, MAPE ~5%  (best-in-class)
#   'MAPE_15'  Additive AR(1) noise, MAPE ~15% (2022 volatile-period equivalent)
#
# Only affects LP_OPTIMISED production forecast (production_forecast_lp.py).
# Settlement always uses the real Day_Ahead_Price_EUR_MWh column.
# Generated by generate_da_price_forecasts.py into
# Input/da_price_forecasts.xlsx and loaded by load_data().
DA_PRICE_FORECAST = 'MAPE_15'  # 'PERFECT' | 'MAPE_05' | 'MAPE_15'

# ---------------------------------------------------------------------------
#  BATTERY SETTINGS
# ---------------------------------------------------------------------------
#
#   BATTERY_ACTIVE  : True  — run battery dispatch after hydro each day
#                     False — hydro only
#   BATTERY_MODE    : 'DAY_AHEAD' — buy low / sell high on the DA market (LP)
#                     'INTRADAY'  — reservoir-triggered co-simulation (reduces intraday imbalance)
#
BATTERY_ACTIVE = False
BATTERY_MODE   = 'INTRADAY'  # 'DAY_AHEAD', 'INTRADAY'

# ---------------------------------------------------------------------------
#  FINANCIAL PARAMETERS  (battery investment analysis)
# ---------------------------------------------------------------------------
#
#   BATTERY_COST_PER_KWH   : 500 EUR/kWh  — Needs to be updated with real market data for accurate analysis.
#   BATTERY_LIFETIME_YEARS : 15 years     — assumed useful life
#   DISCOUNT_RATE          : 0.05         — 5% annual discount rate // NEEDS to be checked
#   BATTERY_DEG_PER_CYCLE  : fraction of capacity lost per full cycle
#                            e.g. 0.0001 = 0.01 %/cycle → 80 % remaining after 2 000 cycles
#   BATTERY_OM_EUR_KWH_YEAR: EUR/kWh/year — O&M cost per unit of installed capacity
#                            e.g. 8.0 EUR/kWh/year → 8000 EUR/year for a 1000 kWh battery
#
BATTERY_COST_PER_KWH    = 300.0    # EUR/kWh
BATTERY_LIFETIME_YEARS  =  15      # years
DISCOUNT_RATE           = 0.05     # —
BATTERY_DEG_PER_CYCLE   = 0.00005    # fraction/cycle  (0.005 %/cycle)
BATTERY_OM_EUR_KWH_YEAR = 8.0     # EUR/kWh/year (8 could be default)

# End-of-life: battery is considered retired at 80% remaining capacity (industry
# standard for grid-tied storage). Used to derive the LP cycle-cost penalty.
EOL_CAPACITY_FRACTION = 0.80

# Battery wear cost — marginal degradation per kWh moved through the battery
# (charge OR discharge). The WATER_VALUE LP uses this as a cycling penalty so
# it only fires the battery when the expected price spread exceeds wear cost.
# Derivation: each cycle (CAPACITY in + CAPACITY out) uses up
# BATTERY_DEG_PER_CYCLE / (1 - EOL_CAPACITY_FRACTION) of the battery's life.
# Per kWh moved through (sum of charge + discharge):
#   CYCLE_COST_EUR_KWH = BATTERY_COST_PER_KWH * BATTERY_DEG_PER_CYCLE
#                       / (2 * (1 - EOL_CAPACITY_FRACTION))
# With defaults: 300 * 0.00005 / (2 * 0.20) = 0.0375 EUR/kWh = 37.5 EUR/MWh per direction
CYCLE_COST_EUR_KWH = (BATTERY_COST_PER_KWH * BATTERY_DEG_PER_CYCLE
                      / (2.0 * (1.0 - EOL_CAPACITY_FRACTION)))

